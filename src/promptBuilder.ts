export interface PromptOptions {
  starterCodeWithBug: boolean;
  testCases: boolean;
  defenseQuestions: boolean;
  gradingRubric: boolean;
}

export interface PromptFormState {
  discipline: string;
  course: number;
  topic: string;
  learningOutcomes: string;
  language: string;
  customLanguage?: string;
  difficulty: 'Базовый' | 'Средний' | 'Повышенный';
  variantsCount: number;
  domains: string;
  options: PromptOptions;
}

export const DEFAULT_FORM_STATE: PromptFormState = {
  discipline: 'Объектно-ориентированное программирование',
  course: 2,
  topic: 'Наследование, полиморфизм и абстрактные классы',
  learningOutcomes:
    'Студент умеет проектировать иерархию классов, переопределять виртуальные методы в производных классах, использовать абстрактные классы и применять полиморфизм при обработке коллекций объектов.',
  language: 'C#',
  customLanguage: '',
  difficulty: 'Средний',
  variantsCount: 3,
  domains: 'Кофейня, прокат самокатов в Алматы, курьерская доставка',
  options: {
    starterCodeWithBug: true,
    testCases: true,
    defenseQuestions: true,
    gradingRubric: true,
  },
};

export function parseDomainsList(domainsRaw: string): string[] {
  const cleaned = (domainsRaw || '')
    .split(/[,;\n]+/)
    .map((item) => item.trim())
    .filter(Boolean);
  if (cleaned.length === 0) {
    return ['Кофейня', 'Прокат самокатов в Алматы', 'Курьерская доставка'];
  }
  return cleaned;
}

export function clampVariantsCount(value: number): number {
  const parsed = Math.round(Number(value));
  if (Number.isNaN(parsed)) return 3;
  return Math.min(10, Math.max(1, parsed));
}

export function buildCollegePrompt(state: PromptFormState): string {
  const discipline = state.discipline.trim() || 'Объектно-ориентированное программирование';
  const course = Math.min(4, Math.max(1, Math.round(Number(state.course) || 2)));
  const topic = state.topic.trim() || 'Разработка модульного приложения по теме занятия';
  const outcomes =
    state.learningOutcomes.trim() ||
    'Применение изученных синтаксических и архитектурных конструкций языка программирования для решения прикладной задачи.';
  const effectiveLang =
    state.language === 'Другой'
      ? (state.customLanguage || '').trim() || 'Указанный преподавателем язык программирования'
      : state.language;
  const difficulty = state.difficulty || 'Средний';
  const variantsCount = clampVariantsCount(state.variantsCount);
  const domainsList = parseDomainsList(state.domains);

  const difficultyGuidance: Record<string, string> = {
    'Базовый':
      'Базовый уровень: фокус на базовом синтаксисе, чётком алгоритме по шагам, минимальной вложенности (1–2 класса/модуля), понятных типах данных и предсказуемых входных значениях.',
    'Средний':
      'Средний уровень: полноценная архитектура из нескольких взаимосвязанных сущностей, валидация входных данных, обработка типичных граничных случаев и чистая декомпозиция.',
    'Повышенный':
      'Повышенный уровень: расширенная архитектура с интерфейсами/абстракциями, обработка нестандартных сценариев и исключений, оптимизация логики и повышенные требования к расширяемости кода.',
  };

  const variantAssignments: string[] = [];
  for (let i = 0; i < variantsCount; i++) {
    const domain = domainsList[i % domainsList.length];
    const suffix =
      i >= domainsList.length
        ? ` (модификация сценария №${Math.floor(i / domainsList.length) + 1})`
        : '';
    variantAssignments.push(`- Вариант №${i + 1}: предметная область «${domain}»${suffix}`);
  }

  const conditionalSections: string[] = [];
  let sectionIndex = 1;

  if (state.options.starterCodeWithBug) {
    conditionalSections.push(
      `4.${sectionIndex}. СТАРТОВЫЙ КОД С TODO И НАМЕРЕННОЙ СКРЫТОЙ ОШИБКОЙ:\n` +
        `Для каждого варианта подготовь компактный стартовый шаблон кода на языке ${effectiveLang}, который:\n` +
        `- содержит каркас основных структур/классов и комментарии // TODO на местах, которые студент должен реализовать самостоятельно;\n` +
        `- включает ровно ОДНУ намеренную скрытую логическую или граничную ошибку (не синтаксическую — код должен компилироваться/запускаться, но выдавать неверный результат на одном из сценариев);\n` +
        `- в отдельном блоке «Блок для преподавателя» кратко укажи, в какой строке/методе каждого варианта заложена ошибка и как её исправить.`
    );
    sectionIndex++;
  }

  if (state.options.testCases) {
    conditionalSections.push(
      `4.${sectionIndex}. НАБОР ТЕСТОВ И ВХОДНЫХ ДАННЫХ (3–5 СЦЕНАРИЕВ):\n` +
        `Для каждого варианта приведи таблицу или список из 3–5 проверочных сценариев:\n` +
        `- 2 стандартных (нормальных) набора входных данных с ожидаемым выводом;\n` +
        `- 1–2 граничных случая (нулевые/предельные значения, пустые коллекции);\n` +
        `- 1 сценарий с некорректными данными или сценарий, выявляющий скрытую ошибку.`
    );
    sectionIndex++;
  }

  if (state.options.defenseQuestions) {
    conditionalSections.push(
      `4.${sectionIndex}. ВОПРОСЫ ДЛЯ УСТНОЙ ЗАЩИТЫ КОДА (ПО 3 НА ВАРИАНТ):\n` +
        `Для каждого варианта сформулируй ровно 3 контрольных вопроса для устной защиты работы:\n` +
        `- Вопрос 1: на понимание предметной логики и потока выполнения собственного кода студента;\n` +
        `- Вопрос 2: «Что изменится в работе программы, если модифицировать условие X или структуру данных Y?»;\n` +
        `- Вопрос 3: на обоснование выбранного архитектурного решения на языке ${effectiveLang} в рамках темы «${topic}».`
    );
    sectionIndex++;
  }

  if (state.options.gradingRubric) {
    conditionalSections.push(
      `4.${sectionIndex}. УНИВЕРСАЛЬНАЯ РУБРИКА ОЦЕНИВАНИЯ НА 10 БАЛЛОВ (5 КРИТЕРИЕВ × 2 БАЛЛА):\n` +
        `Сформируй единую прозрачную таблицу оценивания работы (максимум 10 баллов), где каждый из 5 критериев оценивается в 0, 1 или 2 балла:\n` +
        `1) Реализация основной функциональности и соответствие ТЗ варианта (0–2 балла);\n` +
        `2) Корректное применение концепций темы «${topic}» на языке ${effectiveLang} (0–2 балла);\n` +
        `3) Поиск и устранение скрытой ошибки / прохождение всех тестовых сценариев, включая граничные (0–2 балла);\n` +
        `4) Качество, читаемость, именование сущностей и структура кода (0–2 балла);\n` +
        `5) Устная защита кода и ответы на контрольные вопросы (0–2 балла).`
    );
    sectionIndex++;
  }

  const optionalBlockText =
    conditionalSections.length > 0
      ? `4. ОБЯЗАТЕЛЬНЫЕ ДОПОЛНИТЕЛЬНЫЕ СЕКЦИИ ДЛЯ КАЖДОГО ВАРИАНТА\n${conditionalSections.join('\n\n')}`
      : `4. ДОПОЛНИТЕЛЬНЫЕ СЕКЦИИ\nОграничься формулировкой технического задания, входных/выходных параметров и требований к реализации для каждого варианта без стартового кода, тестов, вопросов защиты и рубрики.`;

  const lines = [
    `# СИСТЕМНЫЙ ПРОМПТ: РАЗРАБОТКА ПРАКТИЧЕСКОГО ЗАДАНИЯ ДЛЯ СТУДЕНТОВ КОЛЛЕДЖА`,
    ``,
    `1. РОЛЬ И КОНТЕКСТ`,
    `Ты — опытный преподаватель-методист профильных IT-дисциплин в техническом колледже и практикующий разработчик.`,
    `Твоя задача — разработать качественное, методически выверенное практическое (лабораторное) задание по программированию с индивидуальными вариантами для студентов.`,
    ``,
    `2. ПАРАМЕТРЫ УЧЕБНОГО ЗАНЯТИЯ`,
    `- Дисциплина: ${discipline}`,
    `- Курс обучения: ${course} курс колледжа`,
    `- Тема занятия: ${topic}`,
    `- Язык программирования: ${effectiveLang}`,
    `- Уровень сложности: ${difficulty}`,
    `- Методический ориентир сложности: ${difficultyGuidance[difficulty] || difficultyGuidance['Средний']}`,
    `- Количество индивидуальных вариантов: ${variantsCount}`,
    `- Планируемые результаты обучения:`,
    `  ${outcomes}`,
    ``,
    `3. ИНДИВИДУАЛИЗАЦИЯ И ЛОКАЛЬНЫЕ ПРЕДМЕТНЫЕ ОБЛАСТИ`,
    `Используй указанные предметные области для распределения практического контекста по вариантам (задачи должны быть приближены к реальным прикладным сервисам и понятны студентам):`,
    ...variantAssignments,
    `Все ${variantsCount} вар. должны быть строго эквивалентны по трудоёмкости и объёму кода, но различаться предметной логикой, сущностями и формулировкой условий.`,
    ``,
    optionalBlockText,
    ``,
    `5. СТРОГИЕ ОГРАНИЧЕНИЯ И ФОРМАТ ВЫВОДА`,
    `- НЕ давай студентам готовое полное решение задачи: итоговый код должен писаться студентом самостоятельно.`,
    `- НЕ используй реальные персональные данные (ФИО студентов, телефоны, ИИН, адреса) в примерах и тестах — используй только нейтральные синтетические тестовые данные.`,
    `- Оформи итоговые варианты в виде понятных структурированных карточек для каждого варианта и сводной таблицы параметров/оценивания, готовых к печати или публикации в LMS колледжа.`,
  ];

  return lines.join('\n');
}
